USE askxuan_diy;
CREATE TABLE IF NOT EXISTS diy_modeling_config (
 id TINYINT NOT NULL PRIMARY KEY,
 api_key_cipher TEXT NOT NULL,
 model VARCHAR(40) NOT NULL DEFAULT 'meshy-7.1',
 revision BIGINT NOT NULL DEFAULT 1,
 updated_by BIGINT NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS diy_modeling_task (
 id CHAR(32) NOT NULL PRIMARY KEY,
 owner_id BIGINT NOT NULL,
 request_id VARCHAR(64) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 photos TEXT NOT NULL,
 model VARCHAR(40) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'queued',
 progress INT NOT NULL DEFAULT 0,
 provider_id VARCHAR(128) NOT NULL DEFAULT '',
 glb_url VARCHAR(2048) NOT NULL DEFAULT '',
 usdz_url VARCHAR(2048) NOT NULL DEFAULT '',
 error_message VARCHAR(300) NOT NULL DEFAULT '',
 attempts INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 next_poll_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY modeling_request (owner_id,request_id),
 KEY modeling_poll (status,next_poll_at)
);
